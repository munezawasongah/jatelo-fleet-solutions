import type { Router } from 'express';
import type { PoolClient } from '@jfs/db';
import { z } from 'zod';
import { guard, requireAuth, tenantDb, type AuthContext } from '../auth/middleware.js';
import { assertFile } from '../http/crud.js';
import { forbidden, notFound, unprocessable } from '../http/errors.js';
import { AnyRow, listRows, rowsOf, type Row } from '../http/resource.js';
import { route } from '../http/route.js';
import { pushToUser } from '../infra/push.js';
import { redis } from '../infra/redis.js';

const BASE = '/api/v1';
const TAG = 'Messaging';
const ATTACH_PURPOSES = ['proof_of_delivery', 'inspection', 'fuel_receipt', 'other', 'vehicle_photo'];

const Send = z.object({
  body: z.string().trim().min(1).max(4000).optional(),
  attachment_file_id: z.uuid().optional(),
  job_id: z.uuid().optional(),
  client_msg_id: z.string().min(8).max(64).optional().describe('Idempotency key generated by the (offline-capable) app'),
});
const History = z.object({
  before: z.iso.datetime({ offset: true }).optional(),
  limit: z.coerce.number().int().min(1).max(200).default(50),
});

const MSG_SELECT = `SELECT m.id, m.driver_id, m.sender_type, m.sender_user_id, u.full_name AS sender_name, m.body, m.attachment_file_id,
  f.original_name AS attachment_name, f.content_type AS attachment_type, m.job_id, j.reference AS job_reference, m.client_msg_id,
  m.sent_at, m.delivered_at, m.read_at
  FROM messages m LEFT JOIN users u ON u.id = m.sender_user_id LEFT JOIN files f ON f.id = m.attachment_file_id LEFT JOIN jobs j ON j.id = m.job_id`;

const isDriver = (a: AuthContext): boolean => a.permissions.has('driver_app:use');

async function myDriver(c: PoolClient, auth: AuthContext): Promise<{ id: string; full_name: string }> {
  const d = (await c.query<{ id: string; full_name: string }>('SELECT id, full_name FROM drivers WHERE user_id = $1 AND deleted_at IS NULL', [auth.userId])).rows[0];
  if (!d) throw forbidden('Your login is not linked to a driver profile');
  return d;
}

async function insertMessage(
  c: PoolClient,
  auth: AuthContext,
  driverId: string,
  body: z.infer<typeof Send>,
): Promise<{ row: Row; duplicate: boolean }> {
  if (!body.body && !body.attachment_file_id) throw unprocessable('A message needs text or an attachment');
  await assertFile(c, body.attachment_file_id, ATTACH_PURPOSES);
  if (body.job_id) {
    const j = await c.query('SELECT 1 FROM jobs WHERE id = $1 AND driver_id = $2 AND deleted_at IS NULL', [body.job_id, driverId]);
    if (!j.rowCount) throw unprocessable('That job is not assigned to this driver', { job_id: body.job_id });
  }
  const ins = await c.query<{ id: string }>(
    `INSERT INTO messages (tenant_id, driver_id, sender_type, sender_user_id, body, attachment_file_id, job_id, client_msg_id)
     VALUES ($1,$2,$3,$4,$5,$6,$7,$8) ON CONFLICT (tenant_id, client_msg_id) WHERE client_msg_id IS NOT NULL DO NOTHING RETURNING id`,
    [auth.tenantId, driverId, isDriver(auth) ? 'driver' : 'user', auth.userId, body.body ?? null, body.attachment_file_id ?? null, body.job_id ?? null,
      body.client_msg_id ?? null],
  );
  const id = ins.rows[0]?.id;
  const row = rowsOf(
    await c.query<Row>(id ? `${MSG_SELECT} WHERE m.id = $1` : `${MSG_SELECT} WHERE m.client_msg_id = $1`, [id ?? body.client_msg_id]),
  )[0]!;
  return { row, duplicate: !id };
}

/** Real-time fan-out: the driver's devices, and every dispatcher socket in the tenant. */
async function fanOut(c: PoolClient, tenantId: string, driverId: string, msg: Row, fromDriver: boolean): Promise<void> {
  const payload = JSON.stringify({ type: 'message', ...msg });
  await redis.publish(`rt:tenant:${tenantId}`, payload);
  const d = (await c.query<{ user_id: string | null; full_name: string }>('SELECT user_id, full_name FROM drivers WHERE id = $1', [driverId])).rows[0];
  if (d?.user_id) await redis.publish(`rt:user:${d.user_id}`, payload);
  if (!fromDriver && d?.user_id)
    await pushToUser(d.user_id, String(msg.sender_name ?? 'Dispatch'), String(msg.body ?? 'Sent an attachment'), {
      type: 'message', message_id: String(msg.id), driver_id: driverId,
    });
}

export function registerMessageRoutes(v1: Router): void {
  // ---------- dispatcher side
  route(v1, BASE, {
    method: 'get',
    path: '/messages/threads',
    tags: [TAG],
    summary: 'Conversation list: one thread per driver with the latest message and unread count',
    auth: true,
    query: z.object({ q: z.string().max(100).optional(), unread: z.enum(['true', 'false']).optional() }),
    middleware: guard('messages:read'),
    responses: { 200: { description: 'Threads', schema: z.object({ data: z.array(AnyRow), unread_total: z.number() }) } },
    handler: async ({ req, query }) => {
      const auth = requireAuth(req);
      if (isDriver(auth)) throw forbidden();
      return tenantDb(req, async (c) => {
        const data = await listRows(
          c,
          `SELECT d.id AS driver_id, d.full_name AS driver_name, d.phone, v.plate_number AS current_vehicle, last.body AS last_body,
             last.sender_type AS last_sender, last.sent_at AS last_at, last.attachment_file_id IS NOT NULL AS last_has_attachment,
             (SELECT count(*) FROM messages x WHERE x.driver_id = d.id AND x.sender_type = 'driver' AND x.read_at IS NULL) AS unread
           FROM drivers d
           JOIN LATERAL (SELECT body, sender_type, sent_at, attachment_file_id FROM messages m WHERE m.driver_id = d.id ORDER BY sent_at DESC LIMIT 1) last ON true
           LEFT JOIN driver_vehicle_assignments dva ON dva.driver_id = d.id AND dva.ends_at IS NULL AND dva.starts_at <= now()
           LEFT JOIN vehicles v ON v.id = dva.vehicle_id
           WHERE d.deleted_at IS NULL AND ($1::text IS NULL OR d.full_name ILIKE '%' || $1 || '%')
           ORDER BY last.sent_at DESC LIMIT 200`,
          [query.q ?? null],
        );
        const filtered = query.unread === 'true' ? data.filter((t) => Number(t.unread) > 0) : data;
        return { data: filtered, unread_total: data.reduce((a, t) => a + Number(t.unread), 0) };
      });
    },
  });

  route(v1, BASE, {
    method: 'get',
    path: '/messages/threads/:driverId',
    tags: [TAG],
    summary: 'Messages with one driver (newest first; page with ?before=)',
    auth: true,
    params: z.object({ driverId: z.uuid() }),
    query: History,
    middleware: guard('messages:read'),
    responses: { 200: { description: 'Messages', schema: z.object({ data: z.array(AnyRow) }) } },
    handler: async ({ req, params, query }) => {
      const auth = requireAuth(req);
      if (isDriver(auth)) throw forbidden();
      return tenantDb(req, async (c) => {
        const d = await c.query('SELECT 1 FROM drivers WHERE id = $1', [params.driverId]);
        if (!d.rowCount) throw notFound('Driver');
        return {
          data: await listRows(
            c,
            `${MSG_SELECT} WHERE m.driver_id = $1 AND ($2::timestamptz IS NULL OR m.sent_at < $2) ORDER BY m.sent_at DESC LIMIT $3`,
            [params.driverId, query.before ?? null, query.limit],
          ),
        };
      });
    },
  });

  route(v1, BASE, {
    method: 'post',
    path: '/messages/threads/:driverId',
    tags: [TAG],
    summary: 'Send a message to a driver (push + real-time)',
    auth: true,
    params: z.object({ driverId: z.uuid() }),
    body: Send,
    status: 201,
    middleware: guard('messages:write'),
    responses: { 201: { description: 'Message', schema: AnyRow } },
    handler: async ({ req, params, body }) => {
      const auth = requireAuth(req);
      if (isDriver(auth)) throw forbidden();
      return tenantDb(req, async (c) => {
        const d = await c.query('SELECT 1 FROM drivers WHERE id = $1 AND deleted_at IS NULL', [params.driverId]);
        if (!d.rowCount) throw notFound('Driver');
        const { row, duplicate } = await insertMessage(c, auth, params.driverId, body);
        if (!duplicate) await fanOut(c, auth.tenantId!, params.driverId, row, false);
        return row;
      });
    },
  });

  route(v1, BASE, {
    method: 'post',
    path: '/messages/threads/:driverId/read',
    tags: [TAG],
    summary: 'Mark the driver\'s messages in this thread as read',
    auth: true,
    params: z.object({ driverId: z.uuid() }),
    middleware: guard('messages:read'),
    responses: { 200: { description: 'Count', schema: z.object({ updated: z.number() }) } },
    handler: async ({ req, params }) => {
      const auth = requireAuth(req);
      if (isDriver(auth)) throw forbidden();
      return tenantDb(req, async (c) => {
        const r = await c.query(
          `UPDATE messages SET read_at = now(), delivered_at = coalesce(delivered_at, now()) WHERE driver_id = $1 AND sender_type = 'driver' AND read_at IS NULL`,
          [params.driverId],
        );
        return { updated: r.rowCount ?? 0 };
      });
    },
  });

  route(v1, BASE, {
    method: 'post',
    path: '/messages/broadcast',
    tags: [TAG],
    summary: 'Send the same message to several drivers (max 200)',
    auth: true,
    body: z.object({ driver_ids: z.array(z.uuid()).min(1).max(200), body: z.string().trim().min(1).max(4000) }),
    status: 201,
    middleware: guard('messages:write'),
    responses: { 201: { description: 'Sent', schema: z.object({ sent: z.number() }) } },
    handler: async ({ req, body }) => {
      const auth = requireAuth(req);
      if (isDriver(auth)) throw forbidden();
      return tenantDb(req, async (c) => {
        const ids = (await c.query<{ id: string }>('SELECT id FROM drivers WHERE id = ANY($1) AND deleted_at IS NULL', [body.driver_ids])).rows.map((r) => r.id);
        for (const id of ids) {
          const { row } = await insertMessage(c, auth, id, { body: body.body });
          await fanOut(c, auth.tenantId!, id, row, false);
        }
        return { sent: ids.length };
      });
    },
  });

  // ---------- driver app side
  route(v1, BASE, {
    method: 'get',
    path: '/messages/my',
    tags: [TAG],
    summary: 'Driver app: my conversation with dispatch (marks incoming as delivered)',
    auth: true,
    query: History.extend({ since: z.iso.datetime({ offset: true }).optional().describe('Only messages after this time (sync)') }),
    middleware: guard('driver_app:use', 'messages:read'),
    responses: { 200: { description: 'Messages', schema: z.object({ data: z.array(AnyRow), unread: z.number() }) } },
    handler: async ({ req, query }) => {
      const auth = requireAuth(req);
      return tenantDb(req, async (c) => {
        const me = await myDriver(c, auth);
        await c.query(`UPDATE messages SET delivered_at = now() WHERE driver_id = $1 AND sender_type <> 'driver' AND delivered_at IS NULL`, [me.id]);
        const data = await listRows(
          c,
          `${MSG_SELECT} WHERE m.driver_id = $1 AND ($2::timestamptz IS NULL OR m.sent_at < $2) AND ($3::timestamptz IS NULL OR m.sent_at > $3)
           ORDER BY m.sent_at DESC LIMIT $4`,
          [me.id, query.before ?? null, query.since ?? null, query.limit],
        );
        const unread = (await c.query<{ n: number }>(`SELECT count(*)::int AS n FROM messages WHERE driver_id = $1 AND sender_type <> 'driver' AND read_at IS NULL`, [me.id])).rows[0]!.n;
        return { data, unread };
      });
    },
  });

  route(v1, BASE, {
    method: 'post',
    path: '/messages/my',
    tags: [TAG],
    summary: 'Driver app: send a message to dispatch (idempotent with client_msg_id)',
    auth: true,
    body: Send,
    status: 201,
    middleware: guard('driver_app:use', 'messages:write'),
    responses: { 201: { description: 'Message', schema: AnyRow } },
    handler: async ({ req, body }) => {
      const auth = requireAuth(req);
      return tenantDb(req, async (c) => {
        const me = await myDriver(c, auth);
        const { row, duplicate } = await insertMessage(c, auth, me.id, body);
        if (!duplicate) await fanOut(c, auth.tenantId!, me.id, row, true);
        return row;
      });
    },
  });

  route(v1, BASE, {
    method: 'post',
    path: '/messages/my/read',
    tags: [TAG],
    summary: 'Driver app: mark messages from dispatch as read',
    auth: true,
    middleware: guard('driver_app:use', 'messages:read'),
    responses: { 200: { description: 'Count', schema: z.object({ updated: z.number() }) } },
    handler: async ({ req }) => {
      const auth = requireAuth(req);
      return tenantDb(req, async (c) => {
        const me = await myDriver(c, auth);
        const r = await c.query(
          `UPDATE messages SET read_at = now(), delivered_at = coalesce(delivered_at, now()) WHERE driver_id = $1 AND sender_type <> 'driver' AND read_at IS NULL`,
          [me.id],
        );
        await redis.publish(`rt:tenant:${auth.tenantId}`, JSON.stringify({ type: 'message_read', driver_id: me.id, at: new Date().toISOString() }));
        return { updated: r.rowCount ?? 0 };
      });
    },
  });
}
